    private static JsonNode lookup(JsonNode claims, String path) {
        JsonNode current = claims;
        for (String key : path.split("\\.")) {
            if (current == null || !current.isObject() || !current.has(key)) {
                return null;
            }
            current = current.get(key);
        }
        return current;
    }

    private static boolean matches(String kind, JsonNode value) {
        if (value == null || !value.isTextual()) {
            return false;
        }
        String text = value.asText();
        int limit = MAP.get("kinds").get(kind).get("maxLength").asInt();
        return text.codePointCount(0, text.length()) <= limit && KINDS.get(kind).matcher(text).matches();
    }

    private static String lower(String value) {
        StringBuilder out = new StringBuilder(value.length());
        for (char c : value.toCharArray()) {
            out.append(c >= 'A' && c <= 'Z' ? (char) (c + 32) : c);
        }
        return out.toString();
    }

    private static JsonNode mapTime(JsonNode claims, JsonNode rule) {
        for (JsonNode path : rule.get("claims")) {
            JsonNode value = lookup(claims, path.asText());
            if (value != null && value.isNumber()) {
                double number = value.asDouble();
                if (number >= 0 && number <= MAX_TIME) {
                    // Whole UTC seconds; the fraction is truncated.
                    return new TextNode(Instant.ofEpochSecond((long) number).toString());
                }
            }
            if (matches("time", value)) {
                return value;
            }
        }
        return null;
    }

    private static JsonNode mapList(JsonNode claims, JsonNode rule) {
        String split = rule.path("split").asText("whitespace");
        int max = rule.get("max").asInt();
        for (JsonNode path : rule.get("claims")) {
            JsonNode value = lookup(claims, path.asText());
            List<JsonNode> items = new ArrayList<>();
            if (value != null && value.isTextual()) {
                if (split.equals("none")) {
                    items.add(value);
                } else {
                    Pattern splitter = split.equals("comma_whitespace") ? COMMA_WHITESPACE : WHITESPACE;
                    for (String piece : splitter.split(value.asText())) {
                        items.add(new TextNode(piece));
                    }
                }
            } else if (value != null && value.isArray()) {
                value.forEach(items::add);
            }
            ArrayNode kept = JsonNodeFactory.instance.arrayNode();
            for (JsonNode item : items) {
                if (matches(rule.get("kind").asText(), item) && kept.size() < max) {
                    kept.add(item);
                }
            }
            if (kept.size() > 0) {
                return kept;
            }
        }
        return null;
    }

    private static JsonNode mapRule(JsonNode claims, JsonNode rule) {
        String op = rule.get("op").asText();
        JsonNodeFactory f = JsonNodeFactory.instance;
        switch (op) {
            case "id":
                for (JsonNode path : rule.get("claims")) {
                    JsonNode value = lookup(claims, path.asText());
                    if (matches(rule.get("kind").asText(), value)) {
                        return value;
                    }
                }
                return null;
            case "list":
                return mapList(claims, rule);
            case "time":
                return mapTime(claims, rule);
            case "bool":
                for (JsonNode path : rule.get("claims")) {
                    JsonNode value = lookup(claims, path.asText());
                    if (value != null && value.isBoolean()) {
                        return value;
                    }
                }
                return null;
            case "actor": {
                JsonNode value = lookup(claims, rule.get("claims").get(0).asText());
                if (value != null && value.isObject()) {
                    for (String key : new String[] {"sub", "email"}) {
                        JsonNode item = value.get(key);
                        if (item != null && item.isTextual() && !item.asText().isEmpty()) {
                            return f.booleanNode(true);
                        }
                    }
                    return f.booleanNode(false);
                }
                return f.booleanNode(value != null && value.isTextual() && !value.asText().isEmpty());
            }
            case "mfa_factor_age": {
                JsonNode value = lookup(claims, rule.get("claim").asText());
                int index = rule.get("index").asInt();
                if (value == null || !value.isArray() || value.size() <= index || !value.get(index).isNumber()) {
                    return null;
                }
                double seconds = value.get(index).asDouble() * rule.get("unitSeconds").asDouble();
                if (!(seconds >= 0 && seconds <= rule.get("maxSeconds").asDouble())) {
                    return null;
                }
                ObjectNode mfa = f.objectNode();
                mfa.put("present", true);
                mfa.put("age_seconds", (long) seconds);
                return mfa;
            }
            case "mfa_methods": {
                JsonNode value = lookup(claims, rule.get("claim").asText());
                if (value == null || !value.isArray()) {
                    return null;
                }
                int max = rule.get("max").asInt();
                List<String> kept = new ArrayList<>();
                for (JsonNode item : value) {
                    if (matches(rule.get("kind").asText(), item) && kept.size() < max) {
                        kept.add(item.asText());
                    }
                }
                List<String> ignore = new ArrayList<>();
                rule.get("ignore").forEach(item -> ignore.add(item.asText()));
                ArrayNode methods = f.arrayNode();
                boolean present = false;
                for (String item : kept) {
                    if (lower(item).equals(rule.get("mfaValue").asText())) {
                        present = true;
                    }
                    if (!ignore.contains(lower(item))) {
                        methods.add(item);
                    }
                }
                if (methods.size() == 0) {
                    return null;
                }
                ObjectNode mfa = f.objectNode();
                mfa.put("present", present);
                mfa.set("methods", methods);
                return mfa;
            }
            default:
                throw new IllegalStateException("unknown claim map op " + op);
        }
    }

    private static JsonNode tree(Map<String, ?> value) {
        return value == null ? JsonNodeFactory.instance.objectNode() : PLAIN.valueToTree(value);
    }

    private static AuthContext build(String name, String provider, Map<String, ?> rawClaims, Map<String, ?> rawOverrides) {
        JsonNode claims = tree(rawClaims);
        JsonNode overrides = tree(rawOverrides);
        JsonNode spec = MAP.get("providers").get(name);
        Map<String, JsonNode> rules = new HashMap<>();
        MAP.get("base").fields().forEachRemaining(e -> rules.put(e.getKey(), e.getValue()));
        spec.get("fields").fields().forEachRemaining(e -> rules.put(e.getKey(), e.getValue()));
        if (spec.has("disable")) {
            spec.get("disable").forEach(field -> rules.remove(field.asText()));
        }
        ObjectNode wire = JsonNodeFactory.instance.objectNode();
        wire.put("provider", provider);
        MAP.get("constants").fields().forEachRemaining(e -> wire.set(e.getKey(), e.getValue()));
        for (Map.Entry<String, JsonNode> rule : rules.entrySet()) {
            JsonNode value = mapRule(claims, rule.getValue());
            if (value != null) {
                wire.set(rule.getKey(), value);
            }
        }
        for (Iterator<Map.Entry<String, JsonNode>> it = overrides.fields(); it.hasNext();) {
            Map.Entry<String, JsonNode> override = it.next();
            if (!override.getValue().isNull()) {
                wire.set(override.getKey(), override.getValue());
            }
        }
        JsonNode audiences = wire.get("audiences");
        if (audiences != null && audiences.isArray() && audiences.size() > 0 && !wire.has("audience")) {
            wire.set("audience", audiences.get(0));
        }
        for (String key : new String[] {"issuer", "subject"}) {
            if (!wire.path(key).isTextual() || wire.path(key).asText().isEmpty()) {
                throw new IllegalArgumentException("NoResponse auth context requires a verified issuer and subject");
            }
        }
        try {
            return JSON.getMapper().treeToValue(wire, AuthContext.class);
        } catch (JsonProcessingException e) {
            throw new IllegalArgumentException("NoResponse auth context could not be built: " + e.getOriginalMessage(), e);
        }
    }

